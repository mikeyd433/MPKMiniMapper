local function prof_key(name,bank) return name.."|"..tostring(bank) end

-- Fill up to 8 knob slots using synonym-group keyword matching per slot.
-- Each slot in PARAM_PRIORITIES is a table of synonyms tried in order.
local function autofill_params(profile,track,fx_idx,category)
  if not (track and fx_idx) then return end
  local n=reaper.TrackFX_GetNumParams(track,fx_idx)
  local pnames={}
  for p=0,n-1 do
    local _,pn=reaper.TrackFX_GetParamName(track,fx_idx,p,""); pnames[p]=pn
  end
  local used={}

  -- Iterate params in ascending index order (0..n-1) for deterministic matching.
  -- Using pairs() on the pnames table gives undefined hash-table iteration order,
  -- which means the "first" match changes between runs — fixed by explicit index loop.
  if category=="Drums" then
    for k=1,8 do
      local drum=DRUM_PARTS[k]
      if drum then
        local found=false
        for _,kw in ipairs(drum.kw) do
          if found then break end
          for p=0,n-1 do
            local pn=pnames[p]
            if pn and not used[p] and icontains(pn,kw) then
              profile.knob_params[k]=p; profile.knob_labels[k]=pn
              profile.knob_defaults[k]=reaper.TrackFX_GetParamNormalized(track,fx_idx,p)
              used[p]=true; found=true; break
            end
          end
        end
      end
    end
    return
  end

  local slots=PARAM_PRIORITIES[category] or {}
  for k=1,8 do
    local slot=slots[k]
    if slot then
      local found=false
      for _,kw in ipairs(slot) do
        if found then break end
        for p=0,n-1 do
          local pn=pnames[p]
          if pn and not used[p] and icontains(pn,kw) then
            profile.knob_params[k]=p; profile.knob_labels[k]=pn
            profile.knob_defaults[k]=reaper.TrackFX_GetParamNormalized(track,fx_idx,p)
            used[p]=true; found=true; break
          end
        end
      end
    end
  end

  -- Safety pass: clear any duplicate param_idx assignments that could cause two knobs
  -- to control the same parameter simultaneously.
  local seen_params={}
  for k=1,8 do
    local p=profile.knob_params[k]
    if p and p>=0 then
      if seen_params[p] then
        -- Earlier knob already owns this param — clear this assignment
        profile.knob_params[k]=-1; profile.knob_labels[k]=""
      else
        seen_params[p]=k
      end
    end
  end
end

-- Probe a plugin parameter using adaptive recursive subdivision.
-- Returns: eff_min, eff_max, is_stepped, step_norms
--
-- Phase 1: 64 uniform samples capture the gross shape.
-- Phase 2: each interval where the value changed is recursively halved until
--          the sub-interval is < 1/8192 (≈0.012%) of the full range.  This
--          correctly finds every discrete step no matter how densely packed —
--          including musical-timing parameters whose steps get progressively
--          finer toward zero (e.g. whole → half → quarter → triplet …).
--
-- NOTE: briefly modifies the parameter then restores it — use while not playing.
local function probe_param_range(track, fx, param)
  local NPTS      = 64          -- initial coarse pass
  local MIN_SPAN  = 1 / 8192   -- stop subdividing below this norm width
  local MAX_STEPS = 512         -- safety cap (prevents runaway on continuous params)

  local saved = reaper.TrackFX_GetParamNormalized(track, fx, param)

  local function samp(norm)
    reaper.TrackFX_SetParamNormalized(track, fx, param, clamp(norm,0,1))
    return reaper.TrackFX_GetParam(track, fx, param)
  end

  -- Phase 1: coarse uniform samples
  local coarse = {}
  for i = 0, NPTS do coarse[i] = samp(i / NPTS) end

  -- Phase 2: adaptive subdivision — collect every unique (norm, actual_val) pair.
  -- Stored in a flat list; we push lo-val at norm=0 once, then push hi-val whenever
  -- a new step boundary is found in the recursion.
  local found = {{0, coarse[0]}}

  local function subdivide(lo_n, lo_v, hi_n, hi_v, depth)
    -- Stop if values are the same (no step in this interval) or interval too small
    if math.abs(hi_v - lo_v) < 1e-9 then return end
    if (hi_n - lo_n) < MIN_SPAN or depth > 14 then
      -- Transition detected — record the hi end (the start of the new step)
      if #found < MAX_STEPS then found[#found+1] = {hi_n, hi_v} end
      return
    end
    local mid_n = (lo_n + hi_n) * 0.5
    local mid_v = samp(mid_n)
    subdivide(lo_n, lo_v, mid_n, mid_v, depth+1)
    subdivide(mid_n, mid_v, hi_n, hi_v, depth+1)
  end

  for i = 1, NPTS do
    subdivide((i-1)/NPTS, coarse[i-1], i/NPTS, coarse[i], 0)
  end

  reaper.TrackFX_SetParamNormalized(track, fx, param, saved)

  -- Sort by norm position (subdivision order is depth-first, not sequential)
  table.sort(found, function(a,b) return a[1]<b[1] end)

  -- Deduplicate by actual value (handles floating-point near-duplicates)
  local full_range = math.abs(coarse[NPTS] - coarse[0])
  local val_tol = full_range * 0.0005 + 1e-9
  local uniq = {found[1]}
  for i = 2, #found do
    local v = found[i][2]
    if math.abs(v - uniq[#uniq][2]) > val_tol then
      uniq[#uniq+1] = found[i]
    end
  end

  -- Effective range (skip dead zones at both ends)
  local range_tol = full_range * 0.005 + 1e-6
  local eff_min = 0
  for i = 2, #uniq do
    if math.abs(uniq[i][2] - coarse[0]) > range_tol then
      eff_min = uniq[i-1][1]; break
    end
  end
  local eff_max = 1
  for i = #uniq-1, 1, -1 do
    if math.abs(uniq[i][2] - coarse[NPTS]) > range_tol then
      eff_max = uniq[i+1][1]; break
    end
  end

  -- A parameter is stepped if it has ≥ 2 and ≤ 512 distinct values.
  -- (Continuous params produce hundreds of micro-variations that get deduped to 1.)
  local n = #uniq
  local is_stepped = n >= 2 and n <= MAX_STEPS
  local step_norms = nil
  if is_stepped then
    step_norms = {}
    for _, u in ipairs(uniq) do step_norms[#step_norms+1] = u[1] end
  end
  return eff_min, eff_max, is_stepped, step_norms
end

local function get_profile(plugin_name,bank_id,track,fx_idx)
  local key=prof_key(plugin_name,bank_id)
  if S.plugin_profiles[key] then return S.plugin_profiles[key] end

  local profile={
    knob_params     ={-1,-1,-1,-1,-1,-1,-1,-1},
    knob_labels     ={"","","","","","","",""},
    knob_defaults   ={0,0,0,0,0,0,0,0},   -- normalized value snapshotted on first assignment
    knob_min        ={0,0,0,0,0,0,0,0},   -- normalized lower bound for range
    knob_max        ={1,1,1,1,1,1,1,1},   -- normalized upper bound for range
    knob_relative   ={false,false,false,false,false,false,false,false},
    knob_names      ={"","","","","","","",""},  -- user-editable friendly names
    drum_pad_notes  ={-1,-1,-1,-1,-1,-1,-1,-1},
    drum_pad_labels ={"","","","","","","",""},
    confirmed       =false,
    knob_stepped    ={false,false,false,false,false,false,false,false},
    knob_step_norms ={},
  }

  local cat=S.bank_defs[bank_id] and S.bank_defs[bank_id].category
  if cat then autofill_params(profile,track,fx_idx,cat) end

  -- Flag new drum plugins for the first-time prompt
  if cat=="Drums" then
    S.pending_drum_prompt=plugin_name
  end

  S.plugin_profiles[key]=profile; return profile
end

