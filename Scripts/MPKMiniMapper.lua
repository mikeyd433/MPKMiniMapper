local function config_path()
  local d = reaper.GetProjectPathEx()
  if not d or d=="" then return nil end
  return d:gsub("[/\\]+$","") .. "\\" .. SCRIPT_NAME .. "_config.json"
end

local function save_config()
  local path = config_path()
  if not path then status("Save failed: no project open"); return end
  -- Serialize bank_defs as an array (indices 1-MAX_BANKS, nil = empty slot stored as false sentinel)
  local bd_out={}
  for i=1,MAX_BANKS do
    local b=S.bank_defs[i]
    if b then bd_out[i]={name=b.name, category=b.category, color=b.color,
                          pinned_plugin=b.pinned_plugin}
    else bd_out[i]=false end
  end
  local data = {
    version=VERSION, preset_name=S.preset_name,
    active_bank=S.active_bank, window_mode=S.window_mode,
    knob_ccs=S.knob_ccs, scrub_sensitivity=S.scrub_sensitivity,
    scrub_relative=S.scrub_relative,
    plugin_library=S.plugin_library, plugin_profiles=S.plugin_profiles,
    bank_defs=bd_out,
  }
  local f=io.open(path,"w")
  if f then f:write(json.encode(data)); f:close()
  else status("Save failed: cannot write "..path) end
  S.config_last_save=reaper.time_precise()
end

local function load_config(path)
  path = path or config_path()
  if not path then return end
  local f=io.open(path,"r"); if not f then return end
  local content=f:read("*a"); f:close()
  local data=json.decode(content)
  if type(data)~="table" then status("Config: invalid JSON"); return end
  if data.preset_name        then S.preset_name        = data.preset_name       end
  if data.active_bank        then S.active_bank         = data.active_bank       end
  if data.window_mode        then S.window_mode         = data.window_mode       end
  if data.scrub_sensitivity  then S.scrub_sensitivity   = data.scrub_sensitivity end
  if data.scrub_relative ~= nil then S.scrub_relative  = data.scrub_relative    end
  if data.plugin_library     then S.plugin_library      = data.plugin_library    end
  if data.plugin_profiles    then
    S.plugin_profiles = data.plugin_profiles
    -- JSON encodes sparse integer-keyed tables as objects with string keys ("1","2"...).
    -- Convert them back to integer keys so profile.knob_params[knob] (integer) works.
    local int_keyed = {"knob_params","knob_labels","knob_defaults","knob_min","knob_max",
                       "knob_relative","knob_stepped","knob_step_norms"}
    for _, profile in pairs(S.plugin_profiles) do
      if type(profile) == "table" then
        for _, field in ipairs(int_keyed) do
          local t = profile[field]
          if type(t) == "table" then
            local new = {}
            for k, v in pairs(t) do new[tonumber(k) or k] = v end
            profile[field] = new
          end
        end
        -- knob_step_norms values are themselves arrays; re-index those too
        if type(profile.knob_step_norms) == "table" then
          for k, arr in pairs(profile.knob_step_norms) do
            if type(arr) == "table" then
              local new = {}
              for sk, sv in pairs(arr) do new[tonumber(sk) or sk] = sv end
              profile.knob_step_norms[k] = new
            end
          end
        end
      end
    end
  end
  if type(data.knob_ccs)=="table" then
    for i=1,8 do if data.knob_ccs[i] then S.knob_ccs[i]=data.knob_ccs[i] end end
  end
  -- Load bank_defs: slot 1 is always overwritten with the protected Follow Track entry
  if type(data.bank_defs)=="table" then
    for i=2,MAX_BANKS do
      local b=data.bank_defs[i]
      if type(b)=="table" and type(b.name)=="string" then
        S.bank_defs[i]={name=b.name, category=b.category,
          color=(type(b.color)=="table" and b.color or {0.5,0.5,0.5}),
          pinned_plugin=(type(b.pinned_plugin)=="string" and b.pinned_plugin or nil)}
      else
        S.bank_defs[i]=nil
      end
    end
  end
  status("Config loaded")
end

