local function guess_by_name(name)
  for cat,names in pairs(PLUGIN_NAME_TABLE) do
    for _,n in ipairs(names) do
      if icontains(name,n) then return cat end
    end
  end
end

local function guess_by_params(track,fx_idx)
  local n=reaper.TrackFX_GetNumParams(track,fx_idx)
  local scores={}
  for cat in pairs(PARAM_PRIORITIES) do scores[cat]=0 end
  scores["Drums"]=0
  for p=0,math.min(n-1,40) do
    local _,pn=reaper.TrackFX_GetParamName(track,fx_idx,p,"")
    for cat,slots in pairs(PARAM_PRIORITIES) do
      for _,slot in ipairs(slots) do
        for _,kw in ipairs(slot) do
          if icontains(pn,kw) then scores[cat]=scores[cat]+1 end
        end
      end
    end
    for _,drum in ipairs(DRUM_PARTS) do
      for _,kw in ipairs(drum.kw) do
        if icontains(pn,kw) then scores["Drums"]=scores["Drums"]+1 end
      end
    end
  end
  local best,bs=nil,1
  for cat,score in pairs(scores) do if score>bs then best,bs=cat,score end end
  return best
end

local function lib_entry(name,track,fx_idx)
  local e=S.plugin_library[name]
  if e then
    -- If the entry was auto-created as Unknown but never confirmed by the user,
    -- try the guess again — the plugin name table may have grown since first encounter,
    -- or the entry was saved before parameter scanning was available.
    if e.status~="Confirmed" and (e.confirmed=="Unknown" or not e.confirmed) then
      local g=guess_by_name(name)
      if not g and track and fx_idx then g=guess_by_params(track,fx_idx) end
      if g and g~="Unknown" then
        e.guessed=g; e.confirmed=g; S.config_dirty=true
      end
    end
    return e
  end
  local g=guess_by_name(name)
  if not g and track and fx_idx then g=guess_by_params(track,fx_idx) end
  g=g or "Unknown"
  local e2={guessed=g, confirmed=g, status="Unconfirmed"}
  S.plugin_library[name]=e2; S.config_dirty=true; return e2
end

local function find_fx(track,category)
  if not track then return nil,nil end
  for i=0,reaper.TrackFX_GetCount(track)-1 do
    local _,raw=reaper.TrackFX_GetFXName(track,i,"")
    local name=strip_prefix(raw)
    if lib_entry(name,track,i).confirmed==category then return i,name end
  end
  return nil,nil
end

-- Like find_fx but respects a bank's pinned_plugin field:
-- if set, match by exact plugin name; otherwise fall back to category search.
local function find_fx_for_bank(track,bdef)
  if not track or not bdef then return nil,nil end
  if bdef.pinned_plugin then
    for i=0,reaper.TrackFX_GetCount(track)-1 do
      local _,raw=reaper.TrackFX_GetFXName(track,i,"")
      if strip_prefix(raw)==bdef.pinned_plugin then return i,bdef.pinned_plugin end
    end
    return nil,nil
  end
  return find_fx(track,bdef.category)
end

