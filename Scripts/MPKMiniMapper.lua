                   (S.new_bank_mode=="plugin" and 212 or 140) or 32
  local header_h = 26

  -- Grid tile layout
  local pad=6; local cols=2; local gap=4
  local tile_w=math.floor((w-pad*2-gap*(cols-1))/cols)
  local tile_h=50

  -- Collect occupied slots in order
  local slots={}
  for i=1,MAX_BANKS do if S.bank_defs[i] then slots[#slots+1]=i end end
  local rows=math.ceil(#slots/cols)
  local total_grid_h=rows*(tile_h+gap)

  -- Grid viewport
  local grid_y=y+header_h
  local grid_h=h-header_h-footer_h-6

  -- Mouse-wheel scroll
  local max_scroll=math.max(0,total_grid_h-grid_h)
  if hov(x,grid_y,w,grid_h) then
    local wheel=gfx.mouse_wheel-S.prev_mouse_wheel
    if wheel~=0 then
      S.preset_scroll=clamp(S.preset_scroll-math.floor(wheel/120)*(tile_h+gap),0,max_scroll)
    end
  end
  S.preset_scroll=clamp(S.preset_scroll,0,max_scroll)

  -- Thin scrollbar on right edge when content overflows
  if max_scroll>0 then
    local sb_x=x+w-5; local sb_h=math.max(18,grid_h*grid_h/total_grid_h)
    local sb_y=grid_y+(grid_h-sb_h)*(S.preset_scroll/max_scroll)
    set_col({0.26,0.26,0.32}); gfx.rect(sb_x,grid_y,3,grid_h,1)
    set_col({0.55,0.55,0.62}); gfx.rect(sb_x,sb_y,3,sb_h,1)
  end

  -- Draw tiles
  for bi,slot in ipairs(slots) do
    local bdef=S.bank_defs[slot]
    local row_i=math.ceil(bi/cols)-1      -- 0-indexed row
    local col_i=(bi-1)%cols               -- 0-indexed col
    local tx=x+pad+col_i*(tile_w+gap)
    local ty=grid_y+row_i*(tile_h+gap)-S.preset_scroll

    -- Skip if fully outside clip region
    if ty+tile_h>=grid_y and ty<=grid_y+grid_h then
      local tc=bdef.color or {0.5,0.5,0.5}
      local is_active=(S.active_bank==slot)

      -- Tile background: color-tinted dark
      local fade=is_active and 0.28 or 0.14
      fill_rect(tx,ty,tile_w,tile_h,{
        0.11+tc[1]*fade, 0.11+tc[2]*fade, 0.13+tc[3]*fade})

      -- Left color strip
      set_col(tc); gfx.rect(tx,ty,4,tile_h,1)

      -- Active outline
      if is_active then stroke_rect(tx,ty,tile_w,tile_h,tc) end

      -- Slot number (dimmed top-left)
      draw_str(tx+8,ty+4,tostring(slot),CD,FONT_SMALL)

      -- Bank name
      draw_str(tx+8,ty+16,bdef.name:sub(1,12),CT,FONT_NORMAL)

      -- Category / pinned plugin / Follow Track label
      local cat_label
      if bdef.pinned_plugin then
        cat_label="* "..bdef.pinned_plugin:sub(1,11)
      else
        cat_label=bdef.category or "Follow Track"
      end
      draw_str(tx+8,ty+33,cat_label,CD,FONT_SMALL)

      -- Delete button top-right (slot 1 immune)
      if slot~=BANK_FOLLOW then
        if btn(tx+tile_w-17,ty+4,14,14,"\xc3\x97",{0.55,0.18,0.18}) then
          S.bank_defs[slot]=nil
          if S.active_bank==slot then S.active_bank=1; refresh_knob_labels(S.last_track) end
          S.config_dirty=true
          status("Bank "..slot.." deleted")
        end
      end

      -- Click tile body to switch active bank
      if clicked(tx,ty,tile_w-18,tile_h) then
        S.active_bank=slot
        reset_knob_engagement()
        refresh_knob_labels(S.last_track)
        status("Bank: "..(bdef.name or ""))
      end
    end
  end

  -- Footer: new bank button / creation form (pinned to bottom of panel)
  local fy=y+h-footer_h
  set_col(CBR); gfx.line(x+6,fy,x+w-6,fy,0); fy=fy+6

  if not S.new_bank_form then
    local has_empty=false
    for i=2,MAX_BANKS do if not S.bank_defs[i] then has_empty=true; break end end
    local bc_new=has_empty and {0.20,0.45,0.20} or {0.28,0.28,0.30}
    if btn(x+6,fy,w-12,22,"+ New Bank",bc_new) and has_empty then
      S.new_bank_form=true; S.new_bank_name=""; S.new_bank_cat="Reverb"
    end
    if not has_empty then
      draw_str(x+6,fy+26,"All "..MAX_BANKS.." slots filled",CD,FONT_SMALL)
    end
  else
    -- Inline creation form
    draw_str(x+6,fy+2,"New Bank",CA,FONT_SMALL); fy=fy+20

    -- Name field
    draw_str(x+6,fy+3,"Name:",CD,FONT_SMALL)
    ti_field(x+46,fy,w-52,18,"new_bank_name",S.new_bank_name,function(v)
      S.new_bank_name=v
    end)
    fy=fy+24

    -- Mode toggle: Category vs Plugin
    local mode_col_c=(S.new_bank_mode=="category") and CA or nil
    local mode_col_p=(S.new_bank_mode=="plugin")   and CA or nil
    local hw_mode=math.floor((w-14)/2)
    if btn(x+6,fy,hw_mode,18,"Category",mode_col_c) then S.new_bank_mode="category" end
    if btn(x+8+hw_mode,fy,hw_mode,18,"Plugin",mode_col_p) then
      S.new_bank_mode="plugin"; S.new_bank_plugin_scroll=0
    end
    fy=fy+22

    if S.new_bank_mode=="category" then
      -- Category cycle button
      draw_str(x+6,fy+3,"Type:",CD,FONT_SMALL)
      local cat_idx=1
      for i,c in ipairs(BANK_CATS) do if c==S.new_bank_cat then cat_idx=i; break end end
      if btn(x+46,fy,w-52,18,S.new_bank_cat.." \xe2\x96\xba") then
        cat_idx=(cat_idx%#BANK_CATS)+1; S.new_bank_cat=BANK_CATS[cat_idx]
      end
      fy=fy+24
    else
      -- Plugin picker: all installed plugins (library + project tracks + VST cache files)
      if not S.all_installed_plugins then
        S.all_installed_plugins=scan_installed_plugins()
      end
      local plugins=S.all_installed_plugins
      local list_h=math.min(#plugins,4)*18; if list_h==0 then list_h=18 end
      local max_pscroll=math.max(0,#plugins-4)
      if hov(x+6,fy,w-12,list_h) then
        local wheel=gfx.mouse_wheel-S.prev_mouse_wheel
        if wheel~=0 then
          S.new_bank_plugin_scroll=clamp(
            S.new_bank_plugin_scroll-math.floor(wheel/120),0,max_pscroll)
        end
      end
      fill_rect(x+6,fy,w-12,list_h,CB); stroke_rect(x+6,fy,w-12,list_h,CBR)
      if #plugins==0 then
        draw_str(x+10,fy+3,"No plugins found — try Refresh",CD,FONT_SMALL)
      else
        for i=1,math.min(4,#plugins) do
          local pname=plugins[i+S.new_bank_plugin_scroll]
          if not pname then break end
          local py=fy+(i-1)*18
          local sel=(S.new_bank_plugin==pname)
          if sel then fill_rect(x+6,py,w-12,18,{0.15,0.28,0.45})
          elseif hov(x+6,py,w-12,18) then fill_rect(x+6,py,w-12,18,{0.18,0.20,0.26}) end
          draw_str(x+10,py+3,pname:sub(1,22),sel and CT or CD,FONT_SMALL)
          if clicked(x+6,py,w-12,18) then
            S.new_bank_plugin=pname
            local e=S.plugin_library[pname]
            if e and e.confirmed and e.confirmed~="Unknown" then
              S.new_bank_cat=e.confirmed
            end
          end
        end
      end
      fy=fy+list_h+3
      -- Scroll position indicator + refresh button
      local n_str=tostring(#plugins).." plugins"
      draw_str(x+6,fy+3,n_str,CD,FONT_SMALL)
      if btn(x+w-50,fy,44,16,"Refresh") then
        S.all_installed_plugins=nil; S.new_bank_plugin_scroll=0
      end
      fy=fy+20
      if S.new_bank_plugin~="" then
        draw_str(x+6,fy+2,"\xe2\x86\x92 "..S.new_bank_plugin:sub(1,22),CA,FONT_SMALL)
      else
        draw_str(x+6,fy+2,"Pick a plugin above",CD,FONT_SMALL)
      end
      fy=fy+18
    end

    local hw2=math.floor((w-14)/2)
    local can_create=(S.new_bank_mode=="category") or (S.new_bank_plugin~="")
    if btn(x+6,fy,hw2,22,"Create",can_create and {0.20,0.45,0.20} or {0.28,0.28,0.30}) and can_create then
      local name=(S.new_bank_name~="" and S.new_bank_name or
                  (S.new_bank_mode=="plugin" and S.new_bank_plugin or S.new_bank_cat))
      local slot=nil
      for i=2,MAX_BANKS do if not S.bank_defs[i] then slot=i; break end end
      if slot then
        local pal_idx=((slot-2)%#BANK_PALETTE)+1
        local pinned=(S.new_bank_mode=="plugin" and S.new_bank_plugin~="") and S.new_bank_plugin or nil
        S.bank_defs[slot]={name=name, category=S.new_bank_cat,
                            color=BANK_PALETTE[pal_idx], pinned_plugin=pinned}
        S.config_dirty=true
        status("Bank "..slot..": "..name.." ("..S.new_bank_cat..")")
      end
      S.new_bank_form=false
    end
    if btn(x+8+hw2,fy,hw2,22,"Cancel") then S.new_bank_form=false end
  end
end

-- Draws the open parameter-dropdown list on top of everything else in Setup mode.
-- Called last so it is never covered by other panels.
local function draw_param_dropdown_overlay()
  local dd=S._dd_overlay; if not dd then return end
  S._dd_overlay=nil  -- consumed; draw_param_panel re-sets it each frame while open
  local maxr=10; local rh=20
  local items=#S.param_cache
  if items==0 then return end
  local lh=math.min(maxr,items)*rh
  fill_rect(dd.x,dd.y,dd.w,lh,CP); stroke_rect(dd.x,dd.y,dd.w,lh,CBR)
  local wheel=gfx.mouse_wheel-S.prev_mouse_wheel
  if wheel~=0 and hov(dd.x,dd.y,dd.w,lh) then
    S.dropdown_scroll=clamp(S.dropdown_scroll-math.floor(wheel/120),0,math.max(0,items-maxr))
  end
  for i=1,math.min(maxr,items) do
    local item=S.param_cache[i+S.dropdown_scroll]; if not item then break end
    local py=dd.y+(i-1)*rh
    if hov(dd.x,py,dd.w,rh) then fill_rect(dd.x,py,dd.w,rh,CBTH) end
    draw_str(dd.x+4,py+2,item.name,CT,FONT_SMALL)
    if clicked(dd.x,py,dd.w,rh) then assign_param(dd.k,item.idx,item.name) end
  end
end

