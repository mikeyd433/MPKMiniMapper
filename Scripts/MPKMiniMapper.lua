-- Returns the first bank slot with category "Drums", or 8 as fallback
local function find_drums_bank_slot()
  for i=1,MAX_BANKS do
    if S.bank_defs[i] and S.bank_defs[i].category=="Drums" then return i end
  end
  return 8
