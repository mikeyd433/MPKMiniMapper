-- BANKS 2-7 — PLUGIN CATEGORY BANKS
-- ============================================================

local function plugin_bank_apply(knob,cc_val,track,bank_id)
  if not track then return end
  local bdef_ba=S.bank_defs[bank_id]; if not bdef_ba or not bdef_ba.category then return end
  local fx,pname=find_fx_for_bank(track,bdef_ba); if not fx then return end
  local cat=bdef_ba.category
  local profile=get_profile(pname,bank_id,track,fx)
  -- Ensure knob_defaults exists (profiles loaded from older config files may be missing it)
  if not profile.knob_defaults then profile.knob_defaults={0,0,0,0,0,0,0,0} end
  -- One-time repair: clear duplicate param_idx assignments in profiles loaded from older
  -- config files.  A duplicate means two knobs set the same parameter simultaneously,
  -- appearing as one physical knob controlling two labelled parameters at once.
  if not profile._deduped then
    local seen={}
    for k2=1,8 do
      local p=profile.knob_params[k2]
      if p and p>=0 then
        if seen[p] then
          profile.knob_params[k2]=-1; profile.knob_labels[k2]=""
          S.config_dirty=true
        else seen[p]=k2 end
      end
    end
    profile._deduped=true
  end
  local param=profile.knob_params[knob]
  if not param or param<0 then
    -- Lazy autofill: if this knob has no assignment yet, try to find one now using the
    -- priority keywords. This recovers profiles saved before synonyms were added, or
    -- profiles created before the plugin was confirmed in the library.
    local slots=PARAM_PRIORITIES[cat] or {}
    local slot=slots[knob]
    if slot then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        for _,kw in ipairs(slot) do
          if icontains(pn,kw) then
            local taken=false
            for ok=1,8 do if ok~=knob and profile.knob_params[ok]==p then taken=true; break end end
            if not taken then
              profile.knob_params[knob]=p; profile.knob_labels[knob]=pn
              profile.knob_defaults[knob]=reaper.TrackFX_GetParamNormalized(track,fx,p)
              S.knob_active[knob]=true; refresh_knob_labels(S.last_track)
              param=p; break
            end
          end
        end
        if param and param>=0 then break end
      end
    end
    if not param or param<0 then return end
  end

  local norm=cc_norm(cc_val)
  local lo=profile.knob_min[knob] or 0
  local hi=profile.knob_max[knob] or 1

  -- One-step-per-tick for stepped parameters: each CC event moves the parameter
  -- exactly one step in the direction of knob travel. REAPER snaps automatically.
  -- Works without probing. Falls through to absolute mode when ns_step == 0
  -- (continuous parameter) or when relative mode is selected.
  if not profile.knob_relative[knob] then
    local ns_ok, ns_step, _, ns_large, ns_toggle = reaper.TrackFX_GetParameterStepSizes(track, fx, param)
    -- Only engage for parameters with many fine steps (ns_step <= 0.1 = at least 10 steps).
    -- Coarse selectors (ns_step > 0.1, 2-9 positions) use absolute mode so one tick
    -- doesn't jump half the range.
    if ns_ok and ns_step and ns_step > 0 and ns_step <= 0.1 and not ns_toggle then
      local prev = S.last_cc_raw[knob]
      if cc_val ~= prev then
        local dir = cc_val > prev and 1 or -1
        local cur = reaper.TrackFX_GetParamNormalized(track, fx, param)
        -- Multiplicative stepping: each tick multiplies or divides the current
        -- value by a fixed ratio.  This gives equal relative change at every
        -- position — the same feel as semitones in pitch — and is correct for
        -- any parameter whose values are logarithmically perceived (time, freq).
        -- 2^(1/3) ≈ 1.259 puts three evenly-spaced steps between each doubling
        -- (e.g. 1/4 note → dotted 1/4 → 3/8 → 1/2 note → …).
        -- When the parameter is at zero, bootstrap from one native step up.
        local RATIO = 2^(1/3)
        local base  = (cur > 0) and cur or ns_step
        local new_val = (dir > 0) and (base * RATIO) or (base / RATIO)
        reaper.TrackFX_SetParamNormalized(track, fx, param, clamp(new_val, 0, 1))
      end
      return
    end
  end

  if profile.knob_relative[knob] then
    -- Relative mode: accumulate delta from previous CC value; no soft takeover needed.
    local prev=S.last_cc_raw[knob]
    local cur=reaper.TrackFX_GetParamNormalized(track,fx,param)
    local delta=(cc_val-prev)/127.0*(hi-lo)
    reaper.TrackFX_SetParamNormalized(track,fx,param,clamp(cur+delta,lo,hi))
  else
    -- Absolute mode: soft takeover — don't apply until knob catches up to current value.
    local cur=reaper.TrackFX_GetParamNormalized(track,fx,param)
    -- Express current param as 0-1 on the same scale the knob uses (lo..hi mapped to 0..1)
    local cur_scaled=clamp((cur-lo)/math.max(hi-lo,0.0001),0,1)
    if not check_engaged(knob,cc_val,cur_scaled) then return end
    reaper.TrackFX_SetParamNormalized(track,fx,param,lo+norm*(hi-lo))
  end
end

local function plugin_bank_reset(knob,track,bank_id)
  if not track then return end
  local bdef_br=S.bank_defs[bank_id]; if not bdef_br or not bdef_br.category then return end
  local fx,pname=find_fx_for_bank(track,bdef_br); if not fx then return end
  local profile=get_profile(pname,bank_id,track,fx)
  local param=profile.knob_params[knob]; if param<0 then return end
  local def=profile.knob_defaults and profile.knob_defaults[knob] or 0
  reaper.TrackFX_SetParamNormalized(track,fx,param,def)
end

