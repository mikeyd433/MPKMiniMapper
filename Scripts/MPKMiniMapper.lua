-- Note: K4 (High Pass) and K8 (Low Pass) delegate to the first EQ plugin on
-- the track. REAPER has no native HPF/LPF track property.
-- K3 (Pitch) delegates to the first pitch-shifting plugin found on the track.
-- REAPER's D_PITCH track property only works when item pitch-shift mode is active,
-- which is not reliable in general use, so a plugin is required.

-- Returns (fx_index, param_index) of the main pitch parameter on the track's first
-- pitch-shifting plugin, or nil,nil if none is found.
local function find_pitch_fx(track)
  if not track then return nil,nil end
  local n=reaper.TrackFX_GetCount(track)
  for i=0,n-1 do
    local _,fx_name=reaper.TrackFX_GetFXName(track,i,"")
    if icontains(fx_name,"pitch") or icontains(fx_name,"tune")
    or icontains(fx_name,"transpose") then
      local np=reaper.TrackFX_GetNumParams(track,i)
      for p=0,np-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,i,p,"")
        if icontains(pn,"pitch") or icontains(pn,"semitone")
        or icontains(pn,"shift") or icontains(pn,"transpose") then
          return i,p
        end
      end
    end
  end
  return nil,nil
end

-- ============================================================
-- SOFT TAKEOVER (PICKUP MODE)
-- Prevents parameter jumps when the physical knob position doesn't match the
-- current parameter value (e.g. after switching banks or selecting a new track).
-- The knob is "disengaged" after each bank/track change. While disengaged,
-- incoming CC values are tracked but NOT applied. The knob re-engages the
-- moment the physical position crosses or lands within ±3 steps of the
-- current parameter value.
-- ============================================================

local function reset_knob_engagement()
  for i=1,8 do S.knob_engaged[i]=false end
end

-- Check soft takeover. cur_norm is the current param value expressed as 0-1
-- on the same scale the knob controls (i.e. already mapped through lo/hi).
-- Returns true if the knob should apply; false to skip this event.
local function check_engaged(k, cc_val, cur_norm)
  if S.knob_engaged[k] then return true end
  local cur_cc = clamp(cur_norm*127, 0, 127)
  local prev   = S.last_cc_raw[k]
  -- Engage when the knob crosses the current parameter position (zero snap).
  -- Also engage within 1 CC step so the knob can lock on at the extremes where
  -- crossing is impossible, while keeping the snap to < 0.8% of the range.
  local crossed = (prev-cur_cc)*(cc_val-cur_cc) <= 0
  local near    = math.abs(cc_val-cur_cc) <= 1
  if crossed or near then S.knob_engaged[k]=true; return true end
  return false
end

local function bank1_apply(knob,cc_val,track)
  -- Belt-and-suspenders: this function must never fire while a plugin bank is active.
  -- The call site already guards this, but a double-check prevents K5 scrub from
  -- firing in plugin banks if the code path ever changes.
  if S.active_bank ~= BANK_FOLLOW then return end
  if not track then return end
  local norm=cc_norm(cc_val)
  if knob==1 then
    -- Soft takeover: volume is 0-2 mapped linearly, so cur_norm = D_VOL/2
    local cur=clamp(reaper.GetMediaTrackInfo_Value(track,"D_VOL")/2.0,0,1)
    if not check_engaged(1,cc_val,cur) then return end
    reaper.SetMediaTrackInfo_Value(track,"D_VOL",norm*2.0)
  elseif knob==2 then
    -- Soft takeover: pan -1..+1 mapped to 0..1
    local cur=(reaper.GetMediaTrackInfo_Value(track,"D_PAN")+1.0)*0.5
    if not check_engaged(2,cc_val,cur) then return end
    reaper.SetMediaTrackInfo_Value(track,"D_PAN",norm*2.0-1.0)
  elseif knob==3 then
    local pfx,pp=find_pitch_fx(track)
    if pfx then
      local cur=reaper.TrackFX_GetParamNormalized(track,pfx,pp)
      if not check_engaged(3,cc_val,cur) then return end
      reaper.TrackFX_SetParamNormalized(track,pfx,pp,norm)
    end
  elseif knob==4 then
    local fx=find_fx(track,"EQ")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"high pass") or icontains(pn,"hp freq") or icontains(pn,"highpass")
        or icontains(pn,"hi cut") or icontains(pn,"high cut") or icontains(pn,"hpf")
        or icontains(pn,"hi freq") then
          local cur=reaper.TrackFX_GetParamNormalized(track,fx,p)
          if not check_engaged(4,cc_val,cur) then break end
          reaper.TrackFX_SetParamNormalized(track,fx,p,norm); break
        end
      end
    end
  elseif knob==5 then
    -- Scrub: no soft takeover (relative-style; large-jump guard is already built in)
    if S.scrub_relative then
      -- Relative / infinite mode: hardware knob must be set to relative (increment) mode.
      -- CC values are 2's-complement signed increments centred on 64:
      --   1..63  → right (+1..+63),  65..127 → left (-63..-1),  64/0 → no movement.
      local signed = cc_val <= 63 and cc_val or (cc_val - 128)
      if signed ~= 0 then
        local delta = signed * S.scrub_sensitivity * 0.5
        reaper.SetEditCurPos(math.max(0,reaper.GetCursorPosition()+delta),true,true)
      end
    else
      -- Absolute-delta mode: compute increment from previous CC value.
      -- Ignores jumps > 24 steps on first touch (physical knob far from stored position).
      local prev=S.last_cc_raw[5]
      local raw_delta=cc_val-prev
      if math.abs(raw_delta) < 24 then
        local delta=raw_delta*S.scrub_sensitivity*0.5
        reaper.SetEditCurPos(math.max(0,reaper.GetCursorPosition()+delta),true,true)
      end
    end
  elseif knob==6 then
    local fx=find_fx(track,"Reverb")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"wet") or icontains(pn,"mix") then
          local cur=reaper.TrackFX_GetParamNormalized(track,fx,p)
          if not check_engaged(6,cc_val,cur) then break end
          reaper.TrackFX_SetParamNormalized(track,fx,p,norm); break
        end
      end
    end
  elseif knob==7 then
    local fx=find_fx(track,"Delay")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"wet") or icontains(pn,"mix") then
          local cur=reaper.TrackFX_GetParamNormalized(track,fx,p)
          if not check_engaged(7,cc_val,cur) then break end
          reaper.TrackFX_SetParamNormalized(track,fx,p,norm); break
        end
      end
    end
  elseif knob==8 then
    local fx=find_fx(track,"EQ")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"low pass") or icontains(pn,"lp freq") or icontains(pn,"lowpass")
        or icontains(pn,"lo cut") or icontains(pn,"low cut") or icontains(pn,"lpf")
        or icontains(pn,"lo freq") then
          local cur=reaper.TrackFX_GetParamNormalized(track,fx,p)
          if not check_engaged(8,cc_val,cur) then break end
          reaper.TrackFX_SetParamNormalized(track,fx,p,norm); break
        end
      end
    end
  end
end

local function bank1_reset(knob,track)
  if not track then return end
  if knob==1 then reaper.SetMediaTrackInfo_Value(track,"D_VOL",1.0)
  elseif knob==2 then reaper.SetMediaTrackInfo_Value(track,"D_PAN",0.0)
  elseif knob==3 then
    local pfx,pp=find_pitch_fx(track)
    if pfx then
      local _,_,_=reaper.TrackFX_GetParam(track,pfx,pp)  -- unused but checks param exists
      reaper.TrackFX_SetParamNormalized(track,pfx,pp,0.5)  -- centre = 0 semitones
    end
  elseif knob==4 then
    local fx=find_fx(track,"EQ")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"high pass") or icontains(pn,"highpass")
        or icontains(pn,"hi cut") or icontains(pn,"high cut") or icontains(pn,"hpf")
        or icontains(pn,"hi freq") then
          reaper.TrackFX_SetParamNormalized(track,fx,p,0.0); break  -- min freq
        end
      end
    end
  elseif knob==5 then -- no reset for scrub
  elseif knob==6 then
    local fx=find_fx(track,"Reverb")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"wet") or icontains(pn,"mix") then
          reaper.TrackFX_SetParamNormalized(track,fx,p,0.5); break  -- 50% wet as default
        end
      end
    end
  elseif knob==7 then
    local fx=find_fx(track,"Delay")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"wet") or icontains(pn,"mix") then
          reaper.TrackFX_SetParamNormalized(track,fx,p,0.5); break  -- 50% wet as default
        end
      end
    end
  elseif knob==8 then
    local fx=find_fx(track,"EQ")
    if fx then
      local n=reaper.TrackFX_GetNumParams(track,fx)
      for p=0,n-1 do
        local _,pn=reaper.TrackFX_GetParamName(track,fx,p,"")
        if icontains(pn,"low pass") or icontains(pn,"lowpass")
        or icontains(pn,"lo cut") or icontains(pn,"low cut") or icontains(pn,"lpf")
        or icontains(pn,"lo freq") then
          reaper.TrackFX_SetParamNormalized(track,fx,p,1.0); break  -- max freq
        end
      end
    end
  end
end

